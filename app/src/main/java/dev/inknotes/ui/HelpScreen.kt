/** The guide to every tool and feature: sections on the left, the chosen one on the right; a filter on top. */
@Composable
fun HelpDialog(onDismiss: () -> Unit) {
    Dialog(onDismissRequest = onDismiss, properties = DialogProperties(usePlatformDefaultWidth = false)) {
        Surface(
            shape = MaterialTheme.shapes.extraLarge,
            color = MaterialTheme.colorScheme.surfaceContainerHigh,
            modifier = Modifier.padding(24.dp).widthIn(max = 1100.dp).fillMaxSize(),
        ) {
            var query by remember { mutableStateOf("") }
            var chosen by remember { mutableIntStateOf(0) }
            Column(Modifier.padding(24.dp)) {
                Row(verticalAlignment = Alignment.CenterVertically) {
                    Text("Справка", style = MaterialTheme.typography.headlineSmall, modifier = Modifier.weight(1f))
                    TextButton(onClick = onDismiss) { Text("Закрыть") }
                }
                OutlinedTextField(
                    value = query,
                    onValueChange = { query = it },
                    placeholder = { Text("Найти в справке: «маркер», «PDF», «график»…") },
                    singleLine = true,
                    modifier = Modifier.fillMaxWidth().padding(vertical = 8.dp),
                )
                val q = query.trim()
                if (q.isNotEmpty()) {
                    val found = TOPICS.flatMap { t -> t.entries.filter { (h, b) -> h.contains(q, true) || b.contains(q, true) || t.title.contains(q, true) }.map { t.title to it } }
                    Column(Modifier.fillMaxSize().verticalScroll(rememberScrollState()), verticalArrangement = Arrangement.spacedBy(14.dp)) {
                        if (found.isEmpty()) Text("Ничего не найдено", color = MaterialTheme.colorScheme.onSurfaceVariant)
                        for ((section, entry) in found) Entry(entry.first, entry.second, section)
                    }
                    return@Column
                }
                BoxWithConstraints(Modifier.fillMaxSize()) {
                    if (maxWidth < 640.dp) {
                        // Narrow screen: every section one under another.
                        Column(Modifier.fillMaxSize().verticalScroll(rememberScrollState()), verticalArrangement = Arrangement.spacedBy(14.dp)) {
                            for (t in TOPICS) {
                                Text(t.title, style = MaterialTheme.typography.titleLarge, modifier = Modifier.padding(top = 10.dp))
                                for ((h, b) in t.entries) Entry(h, b)
                            }
                        }
                    } else {
                        Row(Modifier.fillMaxSize()) {
                            Column(Modifier.width(260.dp).fillMaxHeight().verticalScroll(rememberScrollState())) {
                                TOPICS.forEachIndexed { i, t ->
                                    val on = i == chosen
                                    Text(
                                        t.title,
                                        color = if (on) MaterialTheme.colorScheme.onSecondaryContainer else MaterialTheme.colorScheme.onSurface,
                                        fontWeight = if (on) FontWeight.SemiBold else FontWeight.Normal,
                                        modifier = Modifier
                                            .fillMaxWidth()
                                            .clip(RoundedCornerShape(12.dp))
                                            .background(if (on) MaterialTheme.colorScheme.secondaryContainer else androidx.compose.ui.graphics.Color.Transparent)
                                            .clickable { chosen = i }
                                            .padding(horizontal = 14.dp, vertical = 11.dp),
                                    )
                                }
                            }
                            VerticalDivider(Modifier.padding(horizontal = 20.dp), color = MaterialTheme.colorScheme.outlineVariant)
                            val scroll = rememberScrollState()
                            LaunchedEffect(chosen) { scroll.scrollTo(0) }
                            Column(Modifier.weight(1f).fillMaxHeight().verticalScroll(scroll), verticalArrangement = Arrangement.spacedBy(16.dp)) {
                                val t = TOPICS[chosen]
                                Text(t.title, style = MaterialTheme.typography.titleLarge)
                                for ((h, b) in t.entries) Entry(h, b)
                                Spacer(Modifier.height(12.dp))
                            }
                        }
                    }
                }
            }
        }
    }
}

@Composable
private fun Entry(heading: String, body: String, section: String? = null) {
    Column {
        if (section != null) Text(section, style = MaterialTheme.typography.labelMedium, color = MaterialTheme.colorScheme.primary)
        Text(heading, style = MaterialTheme.typography.titleMedium)
        Spacer(Modifier.height(3.dp))
        Text(body, style = MaterialTheme.typography.bodyLarge, color = MaterialTheme.colorScheme.onSurfaceVariant)
        Spacer(Modifier.height(10.dp))
        HorizontalDivider(color = MaterialTheme.colorScheme.outlineVariant.copy(alpha = 0.5f))
    }
}
